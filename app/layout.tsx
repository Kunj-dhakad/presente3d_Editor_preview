/* ================= THEME ================= */

/**
 * `THEMES.dark` ko CSS rule me badalta hai. Palette sirf themes.ts
 * me likhi hai — yahan usi ki copy nahi hai, generate ho rahi hai.
 */
const darkThemeCss = `:root[data-theme="dark"]{${Object.entries(THEMES.dark)
  .map(([key, value]) => `${key}:${value}`)
  .join(";")}}
:root[data-theme="dark"]{color-scheme:dark}
:root[data-theme="light"]{color-scheme:light}`;

/* ================= ROOT LAYOUT ================= */

export default function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  return (
    <html
      lang="en"
      // Theme script hydration se pehle <html> par data-theme aur
      // color-scheme laga deta hai, isliye server HTML client se
      // match nahi karega — ye jaan-boojh ke hai.
      suppressHydrationWarning
      className={`
        ${inter.variable}
        ${lato.variable}
        ${poppins.variable}
        ${roboto.variable}
        ${montserrat.variable}
        ${openSans.variable}
        ${geistSans.variable}
        ${geistMono.variable}
        ${playfair.variable}
      `}
    >
      <head>
        {/* Dark palette ka SOURCE OF TRUTH lib/themes/themes.ts hai.
            Usi object se yahan CSS bana ke bhej rahe hain, taaki pehle
            paint par hi sahi rang lag jaye. Agar sirf applyTheme par
            chhod dete (jo React mount ke baad chalta hai) to reload par
            ek frame light dikhta aur phir dark hota. Palette dobara
            likhne ki zarurat nahi — dono jagah wahi ek object hai. */}
        <style dangerouslySetInnerHTML={{ __html: darkThemeCss }} />
        {/* Ye React se pehle chalti hai aur bas attribute laga deti
            hai, jisse upar wali CSS turant apply ho jaati hai. */}
        <script
          dangerouslySetInnerHTML={{
            __html: `(function(){try{var m=localStorage.getItem("kd-theme");if(m!=="dark"&&m!=="light")m="light";var r=document.documentElement;r.dataset.theme=m;r.style.colorScheme=m;}catch(e){}})();`,
          }}
        />
      </head>
      {/* <body className={`${playfair.className} antialiased`}>
        {children}
      </body> */}
      <body


        className={`${geistSans.variable, inter.className} ${geistMono.variable} antialiased`}

      >
        {children}
      </body>
    </html>
  );
}
